-- 017: время старта процесса runpilot exec (JOB-сессия, 8.1) в записи.
-- /proc/<pid>/stat поле 22 (clock ticks с boot) — сверяется узлом/doctor с
-- фактическим временем старта PID: совпало → тот же процесс (управляемый),
-- не совпало → PID переиспользован другим процессом → вне очереди.
-- В паре с 016 (exec_pid) образует корень EXEC-сессии для правила
-- «кодер вне очереди» (без разбора командной строки).
ALTER TABLE session ADD COLUMN exec_starttime INTEGER NOT NULL DEFAULT 0;
