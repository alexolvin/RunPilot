package proto

// TE-N6 — узел со старой мажорной версией протокола (proto = 1):
// координатор принимает его (совместимость N и N−1), узел работает без
// новых функций, но помечается как «устаревший» ([WARN] + команда
// переустановки). Здесь проверяется правило совместимости Acceptable.

import "testing"

// TestTE_N6 — совместимость по протоколу: текущая (Version) и Version−1
// допустимы; новее или старше — нет. При Version = 2 узел proto = 1
// принимается (работает без новых функций).
func TestTE_N6(t *testing.T) {
	if !Acceptable(Version) {
		t.Errorf("текущая версия (%d) должна приниматься", Version)
	}
	if !Acceptable(Version - 1) {
		t.Errorf("версия %d (N−1) должна приниматься — работает без новых функций", Version-1)
	}
	if Acceptable(Version + 1) {
		t.Errorf("версия %d (новее координатора) не должна приниматься", Version+1)
	}
	if Acceptable(0) {
		t.Errorf("версия 0 (старше N−1) не должна приниматься")
	}
}
